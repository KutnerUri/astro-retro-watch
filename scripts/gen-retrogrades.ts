/**
 * Generates data/retrogrades.json: apparent retrograde periods for each planet.
 *
 * Retrograde = the planet's geocentric apparent ecliptic longitude (true ecliptic
 * of date) is decreasing. We sample the longitude rate daily, find sign changes
 * and bisect each one to about a minute.
 *
 * Run: bun scripts/gen-retrogrades.ts [startYear] [endYear]
 */
import { Body, GeoVector, MakeTime, RotateVector, Rotation_EQJ_ECT, SphereFromVector } from 'astronomy-engine';

const PLANETS = [Body.Mercury, Body.Venus, Body.Mars, Body.Jupiter, Body.Saturn, Body.Uranus, Body.Neptune] as const;

const startYear = Number(process.argv[2] ?? 1900);
const endYear = Number(process.argv[3] ?? 2100);

const J2000_MS = Date.UTC(2000, 0, 1, 12);
const DAY_MS = 86_400_000;
const toUt = (ms: number) => (ms - J2000_MS) / DAY_MS;
const toIso = (ut: number) => new Date(Math.round((ut * DAY_MS + J2000_MS) / 60_000) * 60_000).toISOString().slice(0, 16) + 'Z';

function longitude(body: Body, ut: number): number {
  const time = MakeTime(ut);
  const eqj = GeoVector(body, time, true);
  return SphereFromVector(RotateVector(Rotation_EQJ_ECT(time), eqj)).lon;
}

/** Longitude rate sign, via a centred difference over ±30 minutes. */
const H = 1 / 48;
function rate(body: Body, ut: number): number {
  let d = longitude(body, ut + H) - longitude(body, ut - H);
  if (d > 180) d -= 360;
  if (d < -180) d += 360;
  return d;
}

function bisect(body: Body, a: number, b: number): number {
  let ra = rate(body, a);
  while (b - a > 1 / 1440) {
    const m = (a + b) / 2;
    const rm = rate(body, m);
    if (Math.sign(rm) === Math.sign(ra)) { a = m; ra = rm; } else b = m;
  }
  return (a + b) / 2;
}

// Pad the scan so periods that straddle the range edges are found whole.
const scanStart = toUt(Date.UTC(startYear - 1, 6, 1));
const scanEnd = toUt(Date.UTC(endYear + 1, 6, 1));
const rangeStart = toUt(Date.UTC(startYear, 0, 1));
const rangeEnd = toUt(Date.UTC(endYear + 1, 0, 1));

const planets: Record<string, [string, string, number][]> = {};
for (const body of PLANETS) {
  const periods: [string, string, number][] = [];
  let open: number | null = null;
  let prevT = scanStart;
  let prevR = rate(body, prevT);
  for (let t = scanStart + 1; t <= scanEnd; t += 1) {
    const r = rate(body, t);
    if (prevR > 0 && r <= 0) open = bisect(body, prevT, t);
    else if (prevR < 0 && r >= 0 && open !== null) {
      const close = bisect(body, prevT, t);
      if (close > rangeStart && open < rangeEnd) {
        // How far it walks back: longitude at the first station minus at the second.
        let arc = longitude(body, open) - longitude(body, close);
        if (arc < 0) arc += 360;
        periods.push([toIso(open), toIso(close), Math.round(arc * 100) / 100]);
      }
      open = null;
    }
    prevT = t;
    prevR = r;
  }
  planets[body] = periods;
  console.log(`${body}: ${periods.length} periods`);
}

const out = {
  description:
    'Apparent geocentric retrograde periods: [start UTC, end UTC, degrees walked back]. Generated by scripts/gen-retrogrades.ts with astronomy-engine.',
  range: [startYear, endYear],
  planets,
};
await Bun.write(new URL('../data/retrogrades.json', import.meta.url), JSON.stringify(out) + '\n');
